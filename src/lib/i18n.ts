export type MsgKey = keyof (typeof MSG)["en"];

function fill(s: string, vars: Record<string, string | number> = {}) {
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export function t(lang: Lang | string | null | undefined, key: UiKey, vars?: Record<string, string | number>) {
  const l = isLang(lang) ? lang : "en";
  return fill(UI[l][key] ?? UI.en[key], vars);
}

export function m(lang: Lang | string | null | undefined, key: MsgKey, vars?: Record<string, string | number>) {
  const l = isLang(lang) ? lang : "en";
  return fill(MSG[l][key] ?? MSG.en[key], vars);
}

// Script detection for the WhatsApp bot: a student who types in Telugu gets Telugu back.
export function detectScript(text: string): Lang | null {
  if (/[ఀ-౿]/.test(text)) return "te";
  if (/[஀-௿]/.test(text)) return "ta";
  if (/[ऀ-ॿ]/.test(text)) return "hi";
  return null;
}

export function langFromAcceptLanguage(header: string | null | undefined): Lang {
  const h = (header ?? "").toLowerCase();
  for (const part of h.split(",")) {
    const code = part.trim().slice(0, 2);
    if (code === "te" || code === "ta" || code === "hi") return code;
    if (code === "en") return "en";
  }
  return "en";
}
